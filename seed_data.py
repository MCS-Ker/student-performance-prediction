import os
import django

# تهيئة بيئة جانغو حتى نتمكن من استخدام النماذج خارج الخادم
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings")
django.setup()

from students.models import Student, Course, StudentRecord

# حذف سجلات الأداء السابقة فقط، مع الإبقاء على الطلاب والمقررات
StudentRecord.objects.all().delete()
print("تم حذف سجلات الأداء السابقة")

# ------------------------------------------------------------------
# المرحلة الأولى: المقررات
# ------------------------------------------------------------------
courses_data = [
    ("MATH101", "الرياضيات"),
    ("PHYS101", "الفيزياء"),
    ("CS101", "البرمجة"),
]

courses = {}
for code, title in courses_data:
    # get_or_create تجلب السجل إن وُجد، وتنشئه إن لم يوجد
    course, created = Course.objects.get_or_create(code=code, defaults={"title": title})
    courses[title] = course

# ------------------------------------------------------------------
# المرحلة الثانية: تسجيل الطلاب
# هذا ما يفعله المدير في بداية السنة الدراسية
# ------------------------------------------------------------------
students_data = [
    ("S001", "محمد أمين"),
    ("S002", "ساره محمود"),
    ("S003", "باسم العمر"),
    ("S004", "رائد ماضي"),
    ("S005", "مايا شاهين"),
    ("S006", "ليلى ابراهيم"),
    ("S007", "يوسف سلمان"),
    ("S008", "عمر موسى"),
    ("S009", "منار سعيد"),
    ("S010", "عصام احمد"),
    ("S011", "لينا خوري"),
    ("S012", "كريم عبد الله"),
    ("S013", "نور حسن"),
    ("S014", "جود الحلبي"),
    ("S015", "دانا سالم"),
    ("S016", "هبة رستم"),
    ("S017", "زيد العلي"),
    ("S018", "ريم قاسم"),
    ("S019", "ملك حيدر"),
    ("S020", "فادي عيسى"),
]

students = {}
for student_id, name in students_data:
    # المطابقة بالرقم الجامعي لأنه الحقل الفريد
    student, created = Student.objects.get_or_create(
        student_id=student_id,
        defaults={"name": name}
    )
    students[student_id] = student

# ------------------------------------------------------------------
# المرحلة الثالثة: إدخال البيانات الدراسية
# هذا ما يفعله المدرس أثناء الفصل
# ملاحظة: 14 طالباً فقط أُدخلت بياناتهم، والباقي لم يُدخلوا بعد
# ------------------------------------------------------------------
# الرقم الجامعي، المقرر، الغيابات، وقت الدراسة، تقييم الفترة الأولى، تقييم الفترة الثانية
records_data = [
    # الرياضيات
    ("S013", "الرياضيات",  2, 3, 16.0, 17.0),   # نور حسن - متفوق
    ("S011", "الرياضيات",  5, 2, 13.0, 14.0),   # لينا خوري - جيد
    ("S007", "الرياضيات", 17, 3, 12.0, 12.5),   # يوسف سلمان - غياب مرتفع ودرجات جيدة
    ("S002", "الرياضيات", 13, 2,  9.5, 10.0),   # ساره محمود - غياب مرتفع وخطر متوسط
    ("S008", "الرياضيات",  4, 2,  8.5,  8.0),   # عمر موسى - غياب منخفض وخطر مرتفع
    ("S004", "الرياضيات", 10, 2,  7.0,  6.5),   # رائد ماضي - خطر مرتفع دون تنبيه غياب

    # الفيزياء
    ("S001", "الفيزياء",   3, 4, 12.5, 13.0),   # محمد أمين - جيد
    ("S012", "الفيزياء",   4, 3, 14.0, 14.5),   # كريم عبد الله - متفوق
    ("S003", "الفيزياء",   6, 2, 11.0, 12.0),   # باسم العمر - مقبول
    ("S005", "الفيزياء",   7, 3, 10.2, 11.5),   # مايا شاهين - مقبول
    ("S015", "الفيزياء",   9, 2, 10.0,  9.5),   # دانا سالم - خطر متوسط

    # البرمجة
    ("S018", "البرمجة",    2, 4, 17.0, 17.5),   # ريم قاسم - الأعلى في النظام
    ("S009", "البرمجة",   10, 2, 10.0,  9.5),   # منار سعيد - خطر متوسط
    ("S016", "البرمجة",   12, 2,  8.0,  9.0),   # هبة رستم - عند حد الغياب تماماً
]

for student_id, course_title, absences, studytime, g1, g2 in records_data:

    # تفكيك التقييم إلى وظيفة واختبار، بحيث يكون وسطيهما مساوياً للقيمة المطلوبة
    assignment1 = g1 + 0.5
    quiz1 = g1 - 0.5
    assignment2 = g2 + 0.5
    quiz2 = g2 - 0.5

    StudentRecord.objects.create(
        student=students[student_id],
        course=courses[course_title],
        absences=absences,
        studytime=studytime,
        assignment1=assignment1,
        quiz1=quiz1,
        assignment2=assignment2,
        quiz2=quiz2,
    )

print("عدد المقررات:", Course.objects.count())
print("عدد الطلاب:", Student.objects.count())
print("عدد سجلات الأداء:", StudentRecord.objects.count())
print("طلاب لم تُدخل بياناتهم بعد:", Student.objects.count() - StudentRecord.objects.count())
print("تم الإدخال بنجاح")