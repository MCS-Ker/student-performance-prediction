# الغاية: تنظيف البيانات وتحضيرها للتدريب
 
import pandas as pd
 
df = pd.read_csv("student-mat.csv", sep=";")
print("عدد الطلاب قبل التنظيف: " + str(len(df)))
 
# ------------------------------------------------------------------
# يكشف القيم الفارغة والصفوف المكررة
# ------------------------------------------------------------------
print("")
print("=== المرحلة 1: الفحص البنيوي ===")
print("القيم المفقودة: " + str(df.isnull().sum().sum()))
print("الصفوف المكررة: " + str(df.duplicated().sum()))
print("لم يُستبعَد أي صفّ في هذه المرحلة")
 
# ------------------------------------------------------------------
# المعيار: درجة نهائية صفر مع غياب مسجَّل صفر
# ------------------------------------------------------------------
print("")
print("=== المرحلة 2: الفحص المنطقي للاتساق ===")
 
inconsistent = (df["G3"] == 0) & (df["absences"] == 0)
print("عدد الصفوف المتناقضة: " + str(inconsistent.sum()))
 
df = df[~inconsistent]
print("عدد الطلاب بعد الاستبعاد: " + str(len(df)))
 
# ------------------------------------------------------------------
# الطالب ناجح إذا كانت درجته النهائية 10 أو أكثر
# ------------------------------------------------------------------
print("")
print("=== المرحلة 3: بناء عمود الهدف ===")
df["Pass"] = (df["G3"] >= 10).astype(int)
print("عدد الناجحين: " + str(df["Pass"].sum()))
print("عدد الراسبين: " + str(len(df) - df["Pass"].sum()))
print("نسبة الناجحين: " + str(round(df["Pass"].mean() * 100, 1)) + "%")
 
# ------------------------------------------------------------------
# الحفظ
# ------------------------------------------------------------------
df.to_csv("clean_data.csv", index=False)
print("")
print("تم حفظ البيانات النظيفة في clean_data.csv")
 
